// 根据职称确定学历层次
function getEducationLevel(title) {
  if (title === '教授') return '博士';
  if (title === '副教授') return '博士';
  if (title === '讲师') return '硕士';
  if (title === '助教') return '硕士';
  return '硕士';
}

// 随机选取数组元素
function pick(arr, count) {
  const shuffled = [...arr].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

function randomOne(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

// 主逻辑
const teachers = db.prepare('SELECT id, name, college, title, research FROM teachers').all();
console.log(`共 ${teachers.length} 位教师需要更新`);

const updateStmt = db.prepare(`
  UPDATE teachers SET
    education = ?, undergraduate = ?, graduate = ?,
    courses = ?, papers = ?, projects = ?,
    achievements = ?, social_roles = ?, bio = ?
  WHERE id = ?
`);

let updated = 0;
const tx = db.transaction(() => {
  for (const t of teachers) {
    const cd = COLLEGE_DATA[t.college];
    if (!cd) continue;

    // 学历信息
    const eduLevel = getEducationLevel(t.title);
    const eduSchool = randomOne(cd.education);
    const undergradSchool = t.title === '教授' || t.title === '副教授'
      ? randomOne(cd.education.filter(s => s !== eduSchool))
      : randomOne(cd.education);
    const education = `${eduSchool}${eduLevel}毕业`;
    const undergraduate = undergradSchool + '本科';
    const graduate = eduSchool + (eduLevel === '博士' ? '博士' : '硕士');

    // 课程（3-6门）
    const courseCount = 3 + Math.floor(Math.random() * 4);
    const courses = pick(cd.courses, courseCount).join('、');

    // 论文（2-4篇）
    const paperCount = 2 + Math.floor(Math.random() * 3);
    const papers = pick(cd.papers, paperCount).join('；');

    // 项目（1-3个）
    const projCount = 1 + Math.floor(Math.random() * 3);
    const projects = pick(cd.projects, projCount).join('；');

    // 成果（1-3项）
    const achCount = 1 + Math.floor(Math.random() * 3);
    const achievements = pick(cd.achievements, achCount).join('\n');

    // 社会兼职（1-2项）
    const socialCount = 1 + Math.floor(Math.random() * 2);
    const socialRoles = pick(cd.social, socialCount).join('；');

    // 个人简介
    const bio = `${t.college}${t.title || '教师'}，${education}，${t.research ? '主要从事' + t.research + '方向的研究' : '从事相关领域的研究与教学工作'}。`;

    updateStmt.run(education, undergraduate, graduate, courses, papers, projects, achievements, socialRoles, bio, t.id);
    updated++;
  }
});

tx();
console.log(`成功更新 ${updated} 位教师信息`);
db.close();
